#!/usr/bin/env python3
"""Generate core/visual/palette.gd from design/tokens.json (the single source of truth)."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
t = json.loads((root / "design/tokens.json").read_text())
L = ["# GENERATED by tools/gen_palette.py from design/tokens.json — do not edit by hand.",
     "class_name Palette", "extends RefCounted", ""]
for grp, vals in t["color"].items():
    for k, v in vals.items():
        L.append(f'const {grp.upper()}_{k.upper().replace("-", "_")} := Color("{v}")')
L.append("")
L.append(f'const TILE := {t["grid"]["tile"]}')
for k, v in t["space"].items(): L.append(f"const SPACE_{k.upper()} := {v}")
for k, v in t["radius"].items(): L.append(f"const RADIUS_{k.upper()} := {v}")
for k, v in t["stroke"].items(): L.append(f"const STROKE_{k.upper()} := {v}")
for k, v in t["font"]["size"].items(): L.append(f"const FONT_{k.upper()} := {v}")
for k, v in t["motion"].items():
    if isinstance(v, (int, float)): L.append(f"const MOTION_{k.upper().replace('-', '_')} := {v}")
L.append("")
L.append("const FAMILY := {")
for k in t["color"]["family"]: L.append(f'\t"{k}": FAMILY_{k.upper()},')
L.append("}")
L.append("")
L.append("static func datatype(t: int) -> Color:")
L.append("\treturn DATA_BOOLEAN if t == DataType.BOOLEAN else DATA_NUMBER")
L.append("")
L.append("static func datatype_dim(t: int) -> Color:")
L.append("\treturn DATA_BOOLEAN_DIM if t == DataType.BOOLEAN else DATA_NUMBER_DIM")
L.append("")
L.append("static func family(f: String) -> Color:")
L.append("\treturn FAMILY.get(f, FAMILY_COMPUTE)")
(root / "core/visual/palette.gd").write_text("\n".join(L) + "\n")
print("wrote core/visual/palette.gd")
